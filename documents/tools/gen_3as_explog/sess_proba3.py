def TABLE(head,rows,hl=()):
    """table in LTR: label column first (left), coloured header row; hl = cells (row,col) to colour"""
    cols='|c|'+'c|'*(len(head)-1)
    s=r'\par\smallskip\begin{LTR}\centering{\renewcommand{\arraystretch}{1.45}\begin{tabular}{%s}\hline'%cols
    s+=r'\rowcolor{cSec!12}'+' & '.join(head)+r'\\\hline '
