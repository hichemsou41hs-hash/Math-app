def TREE2(first,second,probs=None,final=None,W=3.2):
    """tree growing left to right; first=[(label,p)], second=[[(label,p),...] per first node];
    probs on branches when given; final column «الاحتمال» with the products"""
    s=r'\begin{tikzpicture}[font=\small,ev/.style={rounded corners=2pt,fill=cDef!12,draw=cDef,inner sep=2pt,minimum size=6mm},br/.style={draw=cDef!70,thick}]'
    leaves=sum(len(x) for x in second); gap=1.4
    y0=(leaves-1)*gap/2; s+=r'\coordinate (O) at (0,0); \fill[cDef] (O) circle (1.8pt);'
    k=0
    for i,((lab,p),kids) in enumerate(zip(first,second)):
        ys=[y0-(k+j)*gap for j in range(len(kids))]; ym=sum(ys)/len(ys)
        s+=r'\node[ev] (F%d) at (%g,%g){$%s$};'%(i,W,ym,lab)
        s+=r'\draw[br] (O)--(F%d) node[midway,%s,sloped]{$%s$};'%(i,'above' if ym>=0 else 'below',p) if p else r'\draw[br] (O)--(F%d);'%i
        for j,(l2,p2) in enumerate(kids):
            s+=r'\node[ev] (L%d%d) at (%g,%g){$%s$};'%(i,j,2*W,ys[j],l2)
            s+=(r'\draw[br] (F%d)--(L%d%d) node[midway,%s,sloped]{$%s$};'%(i,i,j,'above' if j==0 else 'below',p2)) if p2 else r'\draw[br] (F%d)--(L%d%d);'%(i,i,j)
            if final: s+=r'\node[anchor=west] at (%g,%g){$%s$};'%(2*W+0.6,ys[j],final[k+j])
        k+=len(kids)
    if final: s+=r'\node[anchor=west,font=\small\bfseries] at (%g,%g){\ar{الاحتمال}};'%(2*W+0.6,y0+0.9)
    return r'\par\smallskip\begin{LTR}\centering '+s+r'\end{tikzpicture}\end{LTR}\par '
